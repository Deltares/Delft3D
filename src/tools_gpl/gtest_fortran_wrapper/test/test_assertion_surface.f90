module wrapper_assertion_surface
   use, intrinsic :: iso_c_binding
   use assertions_gtest
   implicit none(type, external)
   private
   public :: passing_documented_surface, failing_documented_surface
contains
   subroutine passing_documented_surface() bind(C)
      call f90_expect_eq(1_c_int32_t, 1_c_int32_t, 'case=expect_eq_i32_r0')
      call f90_expect_eq(1.0_c_float, 1.0_c_float, 'case=expect_eq_f32_r0')
      call f90_expect_eq(1.0_c_double, 1.0_c_double, 'case=expect_eq_f64_r0')
      call f90_expect_eq(.false., .false., 'case=expect_eq_logical_r0')
      call f90_expect_eq(.false._c_bool, .false._c_bool, 'case=expect_eq_bool_r0')
      call f90_expect_ne(1_c_int32_t, 2_c_int32_t, 'case=expect_ne_i32_r0')
      call f90_expect_ne(1.0_c_float, 2.0_c_float, 'case=expect_ne_f32_r0')
      call f90_expect_ne(1.0_c_double, 2.0_c_double, 'case=expect_ne_f64_r0')
      call f90_expect_ne(.false., .true., 'case=expect_ne_logical_r0')
      call f90_expect_ne(.false._c_bool, .true._c_bool, 'case=expect_ne_bool_r0')
      call f90_expect_lt(1_c_int32_t, 2_c_int32_t, 'case=expect_lt_i32_r0')
      call f90_expect_lt(1.0_c_float, 2.0_c_float, 'case=expect_lt_f32_r0')
      call f90_expect_lt(1.0_c_double, 2.0_c_double, 'case=expect_lt_f64_r0')
      call f90_expect_le(1_c_int32_t, 1_c_int32_t, 'case=expect_le_i32_r0')
      call f90_expect_le(1.0_c_float, 1.0_c_float, 'case=expect_le_f32_r0')
      call f90_expect_le(1.0_c_double, 1.0_c_double, 'case=expect_le_f64_r0')
      call f90_expect_gt(2_c_int32_t, 1_c_int32_t, 'case=expect_gt_i32_r0')
      call f90_expect_gt(2.0_c_float, 1.0_c_float, 'case=expect_gt_f32_r0')
      call f90_expect_gt(2.0_c_double, 1.0_c_double, 'case=expect_gt_f64_r0')
      call f90_expect_ge(1_c_int32_t, 1_c_int32_t, 'case=expect_ge_i32_r0')
      call f90_expect_ge(1.0_c_float, 1.0_c_float, 'case=expect_ge_f32_r0')
      call f90_expect_ge(1.0_c_double, 1.0_c_double, 'case=expect_ge_f64_r0')
      call f90_expect_float_eq(1.0_c_float, nearest(1.0_c_float, 1.0_c_float), 'case=expect_float_eq_f32_r0')
      call f90_expect_float_eq([1.0_c_float], [nearest(1.0_c_float, 1.0_c_float)], 'case=expect_float_eq_f32_r1')
      call f90_expect_float_eq(reshape([1.0_c_float], [1, 1]), &
                               reshape([nearest(1.0_c_float, 1.0_c_float)], [1, 1]), 'case=expect_float_eq_f32_r2')
      call f90_expect_double_eq(1.0_c_double, nearest(1.0_c_double, 1.0_c_double), 'case=expect_double_eq_f64_r0')
      call f90_expect_double_eq([1.0_c_double], [nearest(1.0_c_double, 1.0_c_double)], &
                                'case=expect_double_eq_f64_r1')
      call f90_expect_double_eq(reshape([1.0_c_double], [1, 1]), &
                                reshape([nearest(1.0_c_double, 1.0_c_double)], [1, 1]), 'case=expect_double_eq_f64_r2')
      call f90_expect_near(1.0_c_float, nearest(1.0_c_float, 1.0_c_float), 0.25_c_float, 'case=expect_near_f32_r0')
      call f90_expect_near([1.0_c_float], [nearest(1.0_c_float, 1.0_c_float)], 0.25_c_float, &
                           'case=expect_near_f32_r1')
      call f90_expect_near(reshape([1.0_c_float], [1, 1]), reshape([nearest(1.0_c_float, 1.0_c_float)], [1, 1]), &
                           0.25_c_float, 'case=expect_near_f32_r2')
      call f90_expect_near(1.0_c_double, nearest(1.0_c_double, 1.0_c_double), 0.25_c_double, &
                           'case=expect_near_f64_r0')
      call f90_expect_near([1.0_c_double], [nearest(1.0_c_double, 1.0_c_double)], 0.25_c_double, &
                           'case=expect_near_f64_r1')
      call f90_expect_near(reshape([1.0_c_double], [1, 1]), &
                           reshape([nearest(1.0_c_double, 1.0_c_double)], [1, 1]), 0.25_c_double, 'case=expect_near_f64_r2')
      call f90_expect_true(-2_c_int32_t, 'case=expect_true_i32_r0')
      call f90_expect_true([-2_c_int32_t], 'case=expect_true_i32_r1')
      call f90_expect_true(reshape([-2_c_int32_t], [1, 1]), 'case=expect_true_i32_r2')
      call f90_expect_true(.true., 'case=expect_true_logical_r0')
      call f90_expect_true([.true.], 'case=expect_true_logical_r1')
      call f90_expect_true(reshape([.true.], [1, 1]), 'case=expect_true_logical_r2')
      call f90_expect_true(.true._c_bool, 'case=expect_true_bool_r0')
      call f90_expect_true([.true._c_bool], 'case=expect_true_bool_r1')
      call f90_expect_true(reshape([.true._c_bool], [1, 1]), 'case=expect_true_bool_r2')
      call f90_expect_false(0_c_int32_t, 'case=expect_false_i32_r0')
      call f90_expect_false([0_c_int32_t], 'case=expect_false_i32_r1')
      call f90_expect_false(reshape([0_c_int32_t], [1, 1]), 'case=expect_false_i32_r2')
      call f90_expect_false(.false., 'case=expect_false_logical_r0')
      call f90_expect_false([.false.], 'case=expect_false_logical_r1')
      call f90_expect_false(reshape([.false.], [1, 1]), 'case=expect_false_logical_r2')
      call f90_expect_false(.false._c_bool, 'case=expect_false_bool_r0')
      call f90_expect_false([.false._c_bool], 'case=expect_false_bool_r1')
      call f90_expect_false(reshape([.false._c_bool], [1, 1]), 'case=expect_false_bool_r2')
      call f90_expect_streq('same', 'same', 'case=expect_streq_string_r0')
      call f90_expect_strne('left', 'right', 'case=expect_strne_string_r0')
      call f90_expect_strcaseeq('MiXeD', 'mixed', 'case=expect_strcaseeq_string_r0')
      call f90_expect_strcasene('left', 'right', 'case=expect_strcasene_string_r0')
   end subroutine passing_documented_surface

   subroutine failing_documented_surface() bind(C)
      call f90_expect_eq(2_c_int32_t, 1_c_int32_t, 'case=expect_eq_i32_r0')
      call f90_expect_eq(2.0_c_float, 1.0_c_float, 'case=expect_eq_f32_r0')
      call f90_expect_eq(2.0_c_double, 1.0_c_double, 'case=expect_eq_f64_r0')
      call f90_expect_eq(.true., .false., 'case=expect_eq_logical_r0')
      call f90_expect_eq(.true._c_bool, .false._c_bool, 'case=expect_eq_bool_r0')
      call f90_expect_ne(1_c_int32_t, 1_c_int32_t, 'case=expect_ne_i32_r0')
      call f90_expect_ne(1.0_c_float, 1.0_c_float, 'case=expect_ne_f32_r0')
      call f90_expect_ne(1.0_c_double, 1.0_c_double, 'case=expect_ne_f64_r0')
      call f90_expect_ne(.false., .false., 'case=expect_ne_logical_r0')
      call f90_expect_ne(.false._c_bool, .false._c_bool, 'case=expect_ne_bool_r0')
      call f90_expect_lt(1_c_int32_t, 1_c_int32_t, 'case=expect_lt_i32_r0')
      call f90_expect_lt(1.0_c_float, 1.0_c_float, 'case=expect_lt_f32_r0')
      call f90_expect_lt(1.0_c_double, 1.0_c_double, 'case=expect_lt_f64_r0')
      call f90_expect_le(2_c_int32_t, 1_c_int32_t, 'case=expect_le_i32_r0')
      call f90_expect_le(2.0_c_float, 1.0_c_float, 'case=expect_le_f32_r0')
      call f90_expect_le(2.0_c_double, 1.0_c_double, 'case=expect_le_f64_r0')
      call f90_expect_gt(1_c_int32_t, 1_c_int32_t, 'case=expect_gt_i32_r0')
      call f90_expect_gt(1.0_c_float, 1.0_c_float, 'case=expect_gt_f32_r0')
      call f90_expect_gt(1.0_c_double, 1.0_c_double, 'case=expect_gt_f64_r0')
      call f90_expect_ge(1_c_int32_t, 2_c_int32_t, 'case=expect_ge_i32_r0')
      call f90_expect_ge(1.0_c_float, 2.0_c_float, 'case=expect_ge_f32_r0')
      call f90_expect_ge(1.0_c_double, 2.0_c_double, 'case=expect_ge_f64_r0')
      call f90_expect_float_eq(1.0_c_float, 2.0_c_float, 'case=expect_float_eq_f32_r0')
      call f90_expect_float_eq([1.0_c_float], [2.0_c_float], 'case=expect_float_eq_f32_r1')
      call f90_expect_float_eq(reshape([1.0_c_float], [1, 1]), reshape([2.0_c_float], [1, 1]), &
                               'case=expect_float_eq_f32_r2')
      call f90_expect_double_eq(1.0_c_double, 2.0_c_double, 'case=expect_double_eq_f64_r0')
      call f90_expect_double_eq([1.0_c_double], [2.0_c_double], 'case=expect_double_eq_f64_r1')
      call f90_expect_double_eq(reshape([1.0_c_double], [1, 1]), reshape([2.0_c_double], [1, 1]), &
                                'case=expect_double_eq_f64_r2')
      call f90_expect_near(1.0_c_float, 2.0_c_float, 0.25_c_float, 'case=expect_near_f32_r0')
      call f90_expect_near([1.0_c_float], [2.0_c_float], 0.25_c_float, 'case=expect_near_f32_r1')
      call f90_expect_near(reshape([1.0_c_float], [1, 1]), reshape([2.0_c_float], [1, 1]), 0.25_c_float, &
                           'case=expect_near_f32_r2')
      call f90_expect_near(1.0_c_double, 2.0_c_double, 0.25_c_double, 'case=expect_near_f64_r0')
      call f90_expect_near([1.0_c_double], [2.0_c_double], 0.25_c_double, 'case=expect_near_f64_r1')
      call f90_expect_near(reshape([1.0_c_double], [1, 1]), reshape([2.0_c_double], [1, 1]), 0.25_c_double, &
                           'case=expect_near_f64_r2')
      call f90_expect_true(0_c_int32_t, 'case=expect_true_i32_r0')
      call f90_expect_true([0_c_int32_t], 'case=expect_true_i32_r1')
      call f90_expect_true(reshape([0_c_int32_t], [1, 1]), 'case=expect_true_i32_r2')
      call f90_expect_true(.false., 'case=expect_true_logical_r0')
      call f90_expect_true([.false.], 'case=expect_true_logical_r1')
      call f90_expect_true(reshape([.false.], [1, 1]), 'case=expect_true_logical_r2')
      call f90_expect_true(.false._c_bool, 'case=expect_true_bool_r0')
      call f90_expect_true([.false._c_bool], 'case=expect_true_bool_r1')
      call f90_expect_true(reshape([.false._c_bool], [1, 1]), 'case=expect_true_bool_r2')
      call f90_expect_false(-2_c_int32_t, 'case=expect_false_i32_r0')
      call f90_expect_false([-2_c_int32_t], 'case=expect_false_i32_r1')
      call f90_expect_false(reshape([-2_c_int32_t], [1, 1]), 'case=expect_false_i32_r2')
      call f90_expect_false(.true., 'case=expect_false_logical_r0')
      call f90_expect_false([.true.], 'case=expect_false_logical_r1')
      call f90_expect_false(reshape([.true.], [1, 1]), 'case=expect_false_logical_r2')
      call f90_expect_false(.true._c_bool, 'case=expect_false_bool_r0')
      call f90_expect_false([.true._c_bool], 'case=expect_false_bool_r1')
      call f90_expect_false(reshape([.true._c_bool], [1, 1]), 'case=expect_false_bool_r2')
      call f90_expect_streq('left', 'right', 'case=expect_streq_string_r0')
      call f90_expect_strne('same', 'same', 'case=expect_strne_string_r0')
      call f90_expect_strcaseeq('left', 'right', 'case=expect_strcaseeq_string_r0')
      call f90_expect_strcasene('MiXeD', 'mixed', 'case=expect_strcasene_string_r0')
   end subroutine failing_documented_surface

end module wrapper_assertion_surface
